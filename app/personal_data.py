def mask_phone(value: str | None) -> str:
    """Телефон для списка: +7 701 234 56 78 - «+7 70* *** ** 78».

    Видно достаточно, чтобы узнать свой номер, и мало, чтобы позвонить
    по чужому через плечо администратора.
    """
    digits = re.sub(r"\D", "", value or "")
    if not digits:
        return ""
    if len(digits) == 11:
        return f"+{digits[0]} {digits[1:3]}* *** ** {digits[9:]}"
    # Номер записан в незнакомом виде - показываем только две последние цифры.
    return "*" * max(len(digits) - 2, 0) + digits[-2:]


def mask_email(value: str | None) -> str:
    """Почта для списка: ivan@mail.kz - «i***@mail.kz»."""
    value = (value or "").strip()
    if not value:
        return ""
    if "@" not in value:
        return "***"
    local, _, domain = value.partition("@")
    return f"{local[:1]}***@{domain}" if local else f"***@{domain}"


def mask_contact(value: str | None) -> str:
    """Контакт из обращения: человек мог оставить и телефон, и почту."""
    value = (value or "").strip()
    if not value:
        return ""
    return mask_email(value) if "@" in value else mask_phone(value)


# --- Адрес посетителя ------------------------------------------------------

_salt: str | None = None


def ip_salt() -> str:
    """Соль для хеша адреса. Без неё хеш подбирается перебором: адресов
    в интернете хоть и много, но перебрать их все несложно."""
    global _salt
    if _salt is None:
        _salt = os.environ.get("IP_SALT") or read_or_create_secret(".ip_salt")
    return _salt


def hash_ip(ip: str) -> str:
    """Адрес хранится только так. Сравнить два адреса по хешу можно,
    восстановить сам адрес - нет."""
    return hashlib.sha256(f"{ip_salt()}:{ip}".encode("utf-8")).hexdigest()


def looks_like_hash(value: str | None) -> bool:
    return bool(value) and bool(re.fullmatch(r"[0-9a-f]{64}", value))


def short_hash(value: str | None) -> str:
    """Первые знаки хеша - чтобы администратор мог глазами сравнить
    две записи между собой, не видя самого адреса."""
    return (value or "")[:12] or "-"


