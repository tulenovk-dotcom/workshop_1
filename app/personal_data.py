# Слова, из-за которых запись стоит прочитать внимательнее: сведения о
# здоровье - особая категория данных, и в анкете организации или в отзыве
# им не место. Основы слов, а не целые слова: «аутизма», «справку»,
# «инвалидности» должны находиться тоже.
HEALTH_MARKERS = (
    ("аутизм", r"аутиз"),
    ("РАС", r"\bрас\b"),
    ("диагноз", r"диагноз"),
    ("ЗПР", r"\bзпр\b"),
    ("эпилепсия", r"эпилепси"),
    ("инвалидность", r"инвалид"),
    ("справка", r"справк"),
)


def health_markers(*texts: str | None) -> list[str]:
    """Какие слова-маркеры встретились в текстах записи.

    Регистр сворачивает str.lower: в отличие от grep он понимает кириллицу.
    """
    haystack = " ".join(text for text in texts if text).lower()
    return [label for label, pattern in HEALTH_MARKERS if re.search(pattern, haystack)]
