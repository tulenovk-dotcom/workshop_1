"""Какая версия кода сейчас работает.

Понадобилось после случая 05.10.2026: выкат не поднял новую версию и
откатился на прежнюю, сайт при этом продолжал отвечать как ни в чём не
бывало. Снаружи это неотличимо, а узнать было негде.

Версию берём прямо из служебных файлов git в папке сайта - `.git/HEAD` и
ссылку, на которую он указывает. Сам `git` для этого не нужен: это обычные
текстовые файлы. Выкат делает `git reset --hard`, поэтому там всегда тот
коммит, который сейчас развёрнут, - в том числе после отката.

Если папки `.git` нет (код развернули иначе), показываем «не удалось
определить» - честнее, чем выдумывать.

Модуль нарочно ни от чего не зависит и написан без новой записи типов -
чтобы тест на него запускался и там, где само приложение не поднимается.
"""

from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
НЕИЗВЕСТНО = "не удалось определить"


def _прочитать(путь):
    try:
        return путь.read_text(encoding="utf-8", errors="replace").strip()
    except OSError:
        return ""


def current_commit(root=None):
    """Короткий номер текущего коммита или «не удалось определить»."""
    git = Path(root or КОРЕНЬ) / ".git"
    head = _прочитать(git / "HEAD")
    if not head:
        return НЕИЗВЕСТНО

    if head.startswith("ref:"):
        ссылка = head.split(" ", 1)[1].strip()
        commit = _прочитать(git / ссылка)
        if not commit:
            # Ссылка может быть упакована в packed-refs - так бывает после
            # обычного клонирования.
            for строка in _прочитать(git / "packed-refs").splitlines():
                if строка.endswith(" " + ссылка):
                    commit = строка.split(" ", 1)[0]
                    break
    else:
        commit = head

    commit = (commit or "").strip()
    return commit[:7] if len(commit) >= 7 else НЕИЗВЕСТНО
