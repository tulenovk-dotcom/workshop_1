"""Блок платных мест: кто стоит наверху каталога и когда меняется.

Правила решены с владельцем и записаны здесь в одном месте, чтобы их было
видно целиком:

- в блоке не больше трёх карточек;
- блок показывается, только когда в выдаче нашлось хотя бы шесть мест:
  иначе он занял бы почти весь список, и под ним осталась бы пара карточек;
- в блок попадают только те, кто подходит под фильтры родителя и у кого
  оплаченный срок ещё не кончился. Реклама отбирается после фильтров, а не
  до: платное место из другого города родителю не нужно, а центру не нужен
  показ не своему покупателю;
- если оплативших трое или меньше, в блоке стоят все, но порядок не
  закреплён: раз в три часа карточки меняются местами по кругу, и первое
  место по очереди достаётся каждому;
- если оплативших больше трёх, окно из трёх едет по очереди и сдвигается
  каждый час, плюс ещё на одного в сутки. Без суточной добавки при числе
  оплативших, которое делит сутки нацело (двенадцать, восемь, шесть), за
  каждым навсегда закрепились бы одни и те же часы, и кому-то доставалась
  бы только ночь;
- очередь идёт по номеру записи: кто раньше появился в каталоге, тот ближе
  к началу. Порядок постоянный, поэтому и расписание предсказуемое;
- кто сейчас не в блоке, остаётся в обычном списке на своём месте. Из
  списка в блок карточка не копируется, а переносится: дважды на одной
  странице её быть не должно.

Время берётся по Казахстану: иначе блок менялся бы в пять утра, и «сегодня»
на сайте не совпадало бы с «сегодня» у администратора.
"""

from datetime import datetime

from .timeutil import KZ_TIME

# Сколько карточек стоит в блоке.
BLOCK_SIZE = 3

# Сколько карточек должно найтись на странице, чтобы блок вообще появился.
MIN_RESULTS = 6

# Через сколько часов карточки в блоке меняются местами.
SHIFT_HOURS = 3


def now_local() -> datetime:
    return datetime.now(KZ_TIME)


def is_paid(row, today: str) -> bool:
    """Оплачен ли показ у этой записи на сегодня."""
    until = ""
    try:
        until = (row["promo_until"] or "").strip()
    except (IndexError, KeyError, TypeError):
        return False
    return bool(until) and until >= today


def order_step(moment: datetime) -> int:
    """Номер трёхчасового окна в сквозной нумерации.

    Внутри окна порядок в блоке не меняется. Сутки сдвигают очередь не
    ровно на восемь окон, а на одиннадцать: восемь делятся и на двоих
    оплативших, и на четверых, и тогда за каждым навсегда закрепились бы
    одни и те же часы - один всегда первый утром, другой всегда первый
    ночью. Одиннадцать не делится ни на два, ни на три, поэтому очередь
    каждый день съезжает.
    """
    windows_per_day = 24 // SHIFT_HOURS
    return (
        moment.date().toordinal() * (windows_per_day + 3)
        + moment.hour // SHIFT_HOURS
    )


def split(rows, moment: datetime = None):
    """Делит найденные карточки на блок платных мест и обычный список.

    Возвращает пару: карточки блока и всё остальное в прежнем порядке.
    Пустой блок означает, что показывать его не надо совсем.
    """
    moment = moment or now_local()
    today = moment.date().isoformat()
    rows = list(rows)
    if len(rows) < MIN_RESULTS:
        return [], rows

    paid = [r for r in rows if is_paid(r, today)]
    if not paid:
        return [], rows

    if len(paid) <= BLOCK_SIZE:
        # Все оплатившие помещаются в блок, и выбирать не из кого. Но
        # первое место в блоке видно лучше остальных, поэтому порядок
        # сдвигается по кругу раз в три часа: иначе один купивший стоял
        # бы первым всегда, а другой - никогда.
        paid = sorted(paid, key=lambda r: r["id"])
        start = order_step(moment) % len(paid)
        block = [paid[(start + i) % len(paid)] for i in range(len(paid))]
    else:
        paid = sorted(paid, key=lambda r: r["id"])
        # Час даёт сдвиг на одного, сутки - ещё на одного сверх часов.
        step = moment.date().toordinal() * 25 + moment.hour
        start = step % len(paid)
        block = [paid[(start + i) % len(paid)] for i in range(BLOCK_SIZE)]

    chosen = {r["id"] for r in block}
    rest = [r for r in rows if r["id"] not in chosen]
    return block, rest


def promo_cities(counts: dict) -> list:
    """Города, где продвижение имеет смысл предлагать.

    Порог тот же, что и у показа блока: пока в городе меньше шести
    карточек, родитель видит весь список на одном экране, и «первое
    место» там продавать не из чего. Список считается каждый раз заново,
    поэтому город включается сам, как только карточек станет достаточно.
    """
    return sorted(city for city, n in (counts or {}).items() if n >= MIN_RESULTS)
