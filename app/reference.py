def normalize_city(value: str) -> str:
    """Название города в том виде, в каком оно ляжет в базу.

    Пробелы по краям срезаны, внутри схлопнуты, первая буква заглавная.
    Без этого фильтр каталога, который собирает города из карточек,
    показывал бы «алматы», «Алматы » и «Алматы» тремя разными городами.
    """
    city = " ".join(value.split())
    if not city:
        return ""
    return city[0].upper() + city[1:]


